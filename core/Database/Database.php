<?php

declare(strict_types=1);

namespace Core\Database;

use Core\Support\Config;
use PDO;
use PDOException;
use PDOStatement;
use RuntimeException;

/**
 * Lazy, single PDO connection per request plus small query helpers.
 * All helpers use prepared statements — never interpolate user input into SQL.
 */
final class Database
{
    private static ?PDO $pdo = null;

    /** Returns the shared PDO connection, opening it on first use. */
    public static function connection(): PDO
    {
        if (self::$pdo === null) {
            self::$pdo = self::connect();
        }

        return self::$pdo;
    }

    /** Opens the PDO connection and sets charset, collation, time zone and strict SQL mode. */
    private static function connect(): PDO
    {
        $c = Config::get('database');

        $dsn = sprintf(
            '%s:host=%s;port=%d;dbname=%s;charset=%s',
            $c['driver'],
            $c['host'],
            $c['port'],
            $c['name'],
            $c['charset']
        );

        try {
            $pdo = new PDO($dsn, $c['username'], $c['password'], [
                PDO::ATTR_ERRMODE            => PDO::ERRMODE_EXCEPTION,
                PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
                PDO::ATTR_EMULATE_PREPARES   => false,  // real prepared statements
                PDO::ATTR_STRINGIFY_FETCHES  => false,  // return ints/floats as native types
                PDO::ATTR_TIMEOUT            => 5,      // connection timeout (seconds)
            ]);
        } catch (PDOException $e) {
            // Don't leak credentials/host details to callers; keep the original for logs.
            throw new RuntimeException('Database connection failed.', 500, $e);
        }

        $pdo->exec(sprintf(
            "SET NAMES %s COLLATE %s, time_zone = %s, sql_mode = 'STRICT_ALL_TABLES,NO_ZERO_DATE,NO_ZERO_IN_DATE,ERROR_FOR_DIVISION_BY_ZERO,NO_ENGINE_SUBSTITUTION'",
            $pdo->quote($c['charset']),
            $pdo->quote($c['collation']),
            $pdo->quote($c['timezone'])
        ));

        return $pdo;
    }

    /** Prepares and executes a statement with bound parameters; returns the PDOStatement. */
    public static function query(string $sql, array $params = []): PDOStatement
    {
        $stmt = self::connection()->prepare($sql);
        $stmt->execute($params);

        return $stmt;
    }

    /** Returns the first row as an associative array, or null when nothing matches. */
    public static function fetch(string $sql, array $params = []): ?array
    {
        $row = self::query($sql, $params)->fetch();

        return $row === false ? null : $row;
    }

    /** Returns all matching rows as a list of associative arrays. */
    public static function fetchAll(string $sql, array $params = []): array
    {
        return self::query($sql, $params)->fetchAll();
    }

    /** Executes INSERT/UPDATE/DELETE and returns the affected row count. */
    public static function execute(string $sql, array $params = []): int
    {
        return self::query($sql, $params)->rowCount();
    }

    /** Id generated by the last INSERT on this connection. */
    public static function lastInsertId(): int
    {
        return (int) self::connection()->lastInsertId();
    }

    /**
     * Runs $callback inside a transaction; commits on success, rolls back on any throwable.
     */
    public static function transaction(callable $callback): mixed
    {
        $pdo = self::connection();
        $pdo->beginTransaction();

        try {
            $result = $callback($pdo);
            $pdo->commit();
            return $result;
        } catch (\Throwable $e) {
            if ($pdo->inTransaction()) {
                $pdo->rollBack();
            }
            throw $e;
        }
    }

    /**
     * Name of the unique index a MySQL "Duplicate entry" error (SQLSTATE 23000, code 1062) hit,
     * e.g. "users.users_username_unique"; '' when the message doesn't say; null when $e is not a
     * duplicate-key error. The duplicated value itself is never returned, so it can be logged safely.
     */
    public static function duplicateKeyIndex(\Throwable $e): ?string
    {
        if (!$e instanceof PDOException || (int) ($e->errorInfo[1] ?? 0) !== 1062) {
            return null;
        }

        // MySQL 8: "Duplicate entry 'ali' for key 'users.users_username_unique'"
        return preg_match("/for key '([^']+)'/", $e->getMessage(), $m) ? $m[1] : '';
    }

    /**
     * Column behind a duplicate-key error, read from the index naming convention
     * <table>_<column>_unique used by the migrations (users_username_unique => "username").
     * Returns '' when the index doesn't follow that convention (internal or unnamed indexes),
     * or null when $e is not a duplicate-key error.
     */
    public static function duplicateKeyColumn(\Throwable $e): ?string
    {
        $index = self::duplicateKeyIndex($e);
        if ($index === null || $index === '') {
            return $index;
        }

        [$table, $name] = str_contains($index, '.') ? explode('.', $index, 2) : ['', $index];

        if (!str_ends_with($name, '_unique') || ($table !== '' && !str_starts_with($name, $table . '_'))) {
            return '';
        }

        $column = substr($name, $table === '' ? 0 : strlen($table) + 1, -strlen('_unique'));
        return $column;
    }

    /** Closes the connection; the next call to connection() opens a new one. */
    public static function disconnect(): void
    {
        self::$pdo = null;
    }
}
